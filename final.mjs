import puppeteer from 'puppeteer-core';
const URL = 'https://romjjjke.github.io/glazov-avto/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
let p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(URL, { waitUntil: 'networkidle2' });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 1100));
await p.screenshot({ path: 'screenshots/desktop-1440.png' });
const top = await p.evaluate(() => document.querySelector('.volt__pin').getBoundingClientRect().top + window.scrollY);
await p.evaluate(y => window.scrollTo(0, y), top + 760);
await new Promise(r => setTimeout(r, 1000));
await p.screenshot({ path: 'screenshots/desktop-scene.png' });
await p.evaluate(() => document.querySelector('#pervye').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/desktop-ten.png' });
await p.evaluate(() => document.querySelector('#cena').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/desktop-price.png' });
await p.close();

p = await b.newPage();
await p.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await p.goto(URL, { waitUntil: 'networkidle2' });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 1100));
await p.screenshot({ path: 'screenshots/mobile-390.png' });
await p.evaluate(() => document.querySelector('.volt').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/mobile-390-scene.png' });
await p.evaluate(() => document.querySelector('#vyzov').scrollIntoView());
await new Promise(r => setTimeout(r, 900));
await p.screenshot({ path: 'screenshots/mobile-390-call.png' });
await p.close();
await b.close();
